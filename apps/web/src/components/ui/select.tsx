import * as React from "react";
import { cn } from "@/lib/utils";

/** Native <select> styled to match the shadcn Input. Chosen over the Radix Select for
 * reliable keyboard/mobile behaviour and straightforward testing in this slice. */
function Select({ className, ...props }: React.ComponentProps<"select">) {
  return (
    <select
      data-slot="select"
      className={cn(
        "h-9 w-full min-w-0 rounded-md border border-input bg-transparent px-3 py-1 text-sm shadow-xs outline-none focus-visible:border-ring focus-visible:ring-[3px] focus-visible:ring-ring/50 disabled:cursor-not-allowed disabled:opacity-50 aria-invalid:border-destructive dark:bg-input/30",
        className,
      )}
      {...props}
    />
  );
}

export { Select };
